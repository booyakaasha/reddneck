package main

/*

context в Go — это пакет и тип данных, предназначенный для управления временем выполнения
и передачи метаданных между горутинами.
Он используется для передачи сигналов отмены, тайм-аутов и других параметров,
которые могут быть важны для контроля выполнения операций, особенно при асинхронных или долгоживущих процессах.

Тип context.Context используется для того, чтобы:

    Ограничить время выполнения операции (с помощью тайм-аутов или дедлайнов).
    Передать сигнал отмены для прерывания операции, когда это необходимо.
    Передать метаданные (ключ-значение) через границы вызовов функций или горутин.



	В Go существует несколько основных видов контекстов, каждый из которых служит для управления разными аспектами выполнения:

    context.Background()
        Это "пустой" контекст, который используется в качестве родительского контекста для других контекстов.
        Обычно применяется в начале выполнения программы или тестов, когда у вас нет других контекстов.

    Пример:

    go

ctx := context.Background()

context.TODO()

    Это также "пустой" контекст, но его используют, когда контекст требуется по API, но вы еще не знаете, какой конкретный контекст использовать.
    Часто используется для обозначения мест в коде, которые нуждаются в доработке (например, в тестах или разработке).

Пример:

go

ctx := context.TODO()

context.WithCancel(parent)

    Создаёт новый контекст, который может быть отменён вручную вызовом функции отмены (cancel). После отмены все горутины или процессы, связанные с этим контекстом, должны завершить выполнение.
    Функция возвращает новый контекст и функцию cancel, которую необходимо вызвать для завершения контекста.

Пример:

go

ctx, cancel := context.WithCancel(context.Background())
defer cancel()

go func() {
    select {
    case <-ctx.Done():
        fmt.Println("Operation canceled")
    }
}()

context.WithTimeout(parent, timeout)

    Этот контекст автоматически отменяется через указанный тайм-аут.
    Это полезно для ограничений по времени на выполнение операций.

Пример:

go

ctx, cancel := context.WithTimeout(context.Background(), 2*time.Second)
defer cancel()

select {
case <-time.After(3 * time.Second):
    fmt.Println("Completed")
case <-ctx.Done():
    fmt.Println("Timeout or cancellation:", ctx.Err())  // ctx.Err() вернет context.DeadlineExceeded
}

context.WithDeadline(parent, deadline)

    Этот контекст работает аналогично WithTimeout, но с конкретным временем дедлайна, по которому операция должна завершиться.
    Дедлайн — это фиксированное время (например, 5 января 2024 года 12:00), после которого контекст автоматически завершится.

Пример:

go

deadline := time.Now().Add(5 * time.Second)
ctx, cancel := context.WithDeadline(context.Background(), deadline)
defer cancel()

context.WithValue(parent, key, value)

    Этот контекст позволяет передавать данные (метаданные) в цепочке вызовов. Он используется для хранения и передачи значений в пределах выполнения программы.
    Применяется, когда нужно передать дополнительные параметры между функциями, не изменяя их сигнатуру.

Пример:

go

    type key string
    ctx := context.WithValue(context.Background(), key("userID"), 123)

    func doSomething(ctx context.Context) {
        userID := ctx.Value(key("userID")).(int)
        fmt.Println("User ID:", userID)
    }

Когда нужно использовать context и зачем?

context нужен в ситуациях, когда:

    Операции могут быть прерваны или отменены.
        Например, при работе с HTTP-запросами, соединениями с базами данных или другими долгими операциями важно иметь возможность отменить их выполнение, если клиент закрыл соединение или если прошло слишком много времени.

    Пример: серверное приложение может отменить обработку запроса, если клиент разорвал соединение или запрос обрабатывается слишком долго.

    Операции имеют ограничение по времени.
        WithTimeout и WithDeadline используются для контроля времени выполнения операций и предотвращения "зависания" процессов.

    Передача метаданных через вызовы функций.
        context.WithValue позволяет передавать дополнительные параметры, такие как идентификаторы пользователя, токены аутентификации и другую служебную информацию через функции и горутины, не изменяя при этом сигнатуру функций.

    Синхронизация горутин и цепочек вызовов.
        Контекст помогает эффективно управлять жизненным циклом нескольких горутин, которые должны быть отменены одновременно.
*/
